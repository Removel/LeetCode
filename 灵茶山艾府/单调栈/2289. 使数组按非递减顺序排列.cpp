#include <stack>
#include <vector>
using namespace std;


class Solution {
public:
/*
一个简单的流程图，内容来自评论区：DP不会就是真的不会
     * [9   1   2   4    3    5    5]
     *
     * 9
     * -----------------------------6
     * ------------------------5
     * -------------4
     * -------------------3
     * --------2
     * ----1
     *
     *---------------------------------
     * 单调递减栈
     *到 1 的时候 9 在队列中 所以 1是 需要被删除的 时间点为 1
     *到 2 的时候 9 1 在队列中,要删除2需要先删除1, 时间点为 t(1)+1
     *到 4 的时候 9 2 在队列中,要删除4需要先删除2, 时间点为 t(2)+1
     *到 3 的时候 9 4 在队列中,要删除3不需要先删除其他的值,所以删除3的时间点为1
     *到 5 的时候 9 4 3 在队列中,要删除5 需要先删除 4,3,所以删除5的时间点为t(4)+1
     *到 6 的时候 9 5 在队列中,要删除6 需要先删除 5,所以删除6的时间点为t(5)+1
*/
    int totalSteps(vector<int>& nums) {
        int steps = 0;                        // 记录总操作数（即最大轮数）
        vector<int> dp(nums.size(), 0);       // dp[i] 表示 nums[i] 被移除时是在第几轮
        stack<int> st;                        // 单调递减栈，存储元素下标
        
        for(int i = 0; i < nums.size(); ++i) {
            int tmp = 0;                      // 记录当前元素能"消灭"的元素中，最大的轮数
            // 这里维护递减栈
            // 注意：使用 <= 表示相等时也会消灭（左边相等元素会被右边更晚的消灭）
            while(!st.empty() && nums[st.top()] <= nums[i]) {
                // 更新 tmp 为被消灭元素中 dp 值的最大值，即记录如果当前元素会被消灭，那么它在第几轮之后
                tmp = max(tmp, dp[st.top()]);
                st.pop();                     // 弹出已被"消灭"的元素
            }
            
            // 如果栈非空，说明左边有比当前元素大的数
            // 那么当前元素最终会被左边那个更大的数消灭
            if(!st.empty()) {
                tmp++;                        // 轮数+1（当前元素要在下一轮被消灭）
            }
            // 如果栈为空，说明左边没有比当前元素大的数
            // 当前元素永远不会被消灭，tmp不需要+1
            dp[i] = tmp;                      // 记录当前元素被消灭的轮数
            steps = max(steps, tmp);          // 更新最大轮数（即总操作数）
            st.push(i);                       // 将当前元素下标入栈
        }
        
        return steps;                         // 返回所需的总操作数
    }
};